package phash_test

import (
	"encoding/json"
	"os"
	"reflect"
	"testing"

	"github.com/lbe/go-image-phash/phash"
)

// goldenPipelineCase is one fixture from the golden file in
// ../testdata/pipeline: the options Image::PHash 0.3's pHash method was
// called with and the scalar-context return value (the b2h hex of the bit
// string) for the shared fixture DCT matrix.
type goldenPipelineCase struct {
	Name        string `json:"name"`
	Geometry    string `json:"geometry"`
	Reduce      bool   `json:"reduce"`
	Method      string `json:"method"`
	Mirror      bool   `json:"mirror"`
	MirrorProof bool   `json:"mirrorproof"`
	Hex         string `json:"hex"`
}

// loadPipelineGoldens opens and decodes ../testdata/pipeline/pipeline.json,
// failing the test when the file is missing, malformed, or carries no cases.
// It returns the shared fixture DCT matrix, the resize value, and the golden
// cases.
func loadPipelineGoldens(t *testing.T) (dct []float64, resize int, cases []goldenPipelineCase) {
	t.Helper()
	f, err := os.Open("../testdata/pipeline/pipeline.json")
	if err != nil {
		t.Fatalf("open pipeline goldens: %v", err)
	}
	t.Cleanup(func() {
		if err := f.Close(); err != nil {
			t.Errorf("close pipeline goldens: %v", err)
		}
	})

	var goldens struct {
		Cases  []goldenPipelineCase `json:"cases"`
		DCT    []float64            `json:"dct"`
		Resize int                  `json:"resize"`
	}
	if err := json.NewDecoder(f).Decode(&goldens); err != nil {
		t.Fatalf("decode pipeline goldens: %v", err)
	}
	if len(goldens.Cases) == 0 {
		t.Fatalf("no pipeline golden cases loaded")
	}
	return goldens.DCT, goldens.Resize, goldens.Cases
}

// TestHashFromDCTMatchesPerlPHashScalarGolden verifies that the full bit
// pipeline turns a DCT coefficient vector plus Options into a Hash whose hex
// form matches Image::PHash 0.3's pHash scalar-context return value for the
// same coefficients and options. The goldens in ../testdata/pipeline/
// pipeline.json were generated by driving the real installed Image::PHash 0.3
// pHash method (in scalar context, so it returns b2h of the bit string)
// through a fake $self carrying the fixed 32x32 row-major DCT fixture shared
// with testdata/mirror and testdata/methods (DC 100.0 at index 0 plus the
// deterministic AC spread ((i*13)%41)-20), and each case is cross-checked
// against the method goldens for every non-mirror option set. The case
// matrix covers NxN and bit-count geometry, the reduce flag, all five
// methods, the median/average_x extras and the non-reduce NxN skip flag, and
// the mirror and mirrorproof DCT transforms.
func TestHashFromDCTMatchesPerlPHashScalarGolden(t *testing.T) {
	dct, resize, cases := loadPipelineGoldens(t)
	for _, tc := range cases {
		t.Run(tc.Name, func(t *testing.T) {
			got, err := phash.HashFromDCT(dct, resize, phash.Options{
				Geometry:    tc.Geometry,
				Reduce:      tc.Reduce,
				Method:      tc.Method,
				Mirror:      tc.Mirror,
				MirrorProof: tc.MirrorProof,
			})
			if err != nil {
				t.Fatalf("HashFromDCT(%+v) returned an unexpected error: %v", tc, err)
			}
			if got.Hex() != tc.Hex {
				t.Errorf("HashFromDCT(%+v).Hex() = %q, want %q (Image::PHash scalar-context pHash golden)",
					tc, got.Hex(), tc.Hex)
			}
		})
	}
}

// TestHashFromDCTLeavesCallerDCTMatrixUnchanged verifies that hashing never
// mutates the caller's DCT coefficient vector: Image::PHash's threshold
// methods replace the selected coefficients with bits in place, so the Go
// pipeline must copy the selected coefficients (and the mirror/mirrorproof
// transform must return a fresh slice) before any in-place thresholding. The
// test hashes the shared fixture DCT with every golden case's options —
// covering geometry, reduce, method, mirror, and mirrorproof — and requires
// the input slice to be byte-for-byte identical afterwards.
func TestHashFromDCTLeavesCallerDCTMatrixUnchanged(t *testing.T) {
	dct, resize, cases := loadPipelineGoldens(t)
	for _, tc := range cases {
		t.Run(tc.Name, func(t *testing.T) {
			coeffs := append([]float64(nil), dct...)
			before := append([]float64(nil), coeffs...)
			if _, err := phash.HashFromDCT(coeffs, resize, phash.Options{
				Geometry:    tc.Geometry,
				Reduce:      tc.Reduce,
				Method:      tc.Method,
				Mirror:      tc.Mirror,
				MirrorProof: tc.MirrorProof,
			}); err != nil {
				t.Fatalf("HashFromDCT(%+v) returned an unexpected error: %v", tc, err)
			}
			if !reflect.DeepEqual(coeffs, before) {
				t.Errorf("HashFromDCT(%+v) mutated the caller's DCT coefficient matrix (len %d): want the input unchanged", tc, len(coeffs))
			}
		})
	}
}

// TestHashFromDCTRejectsMirrorWithMirrorProof verifies that the mutually
// exclusive mirror and mirrorproof options together return an exclusivity
// error instead of a hash, matching Image::PHash 0.3's _mirroring croak
// ("Options 'mirror' and 'mirrorproof' are mutually exclusive") and the
// Validate contract.
func TestHashFromDCTRejectsMirrorWithMirrorProof(t *testing.T) {
	dct, resize, _ := loadPipelineGoldens(t)
	if _, err := phash.HashFromDCT(dct, resize, phash.Options{
		Geometry:    "8x8",
		Method:      "average",
		Mirror:      true,
		MirrorProof: true,
	}); err == nil {
		t.Fatal("HashFromDCT(Mirror: true, MirrorProof: true) returned a hash with no error; want an exclusivity error (Image::PHash: options mirror and mirrorproof are mutually exclusive)")
	}
}
