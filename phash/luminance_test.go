// goldenLuminanceCase is one fixture from the golden file in
// ../testdata/luminance: the options Image::PHash 0.3's pHash method was
// called with and the scalar-context return value (the b2h hex of the bit
// string) for the shared 32x32 luminance block, hashed by Image::PHash through
// its own Math::DCT dct2d call.
type goldenLuminanceCase struct {
	Name        string `json:"name"`
	Geometry    string `json:"geometry"`
	Reduce      bool   `json:"reduce"`
	Method      string `json:"method"`
	Mirror      bool   `json:"mirror"`
	MirrorProof bool   `json:"mirrorproof"`
	Hex         string `json:"hex"`
}

// loadLuminanceGoldens opens and decodes ../testdata/luminance/luminance.json,
// failing the test when the file is missing, malformed, or carries no cases.
// It returns the shared 32x32 row-major luminance block, the resize value, and
// the golden cases.
func loadLuminanceGoldens(t *testing.T) (luminance []float64, resize int, cases []goldenLuminanceCase) {
	t.Helper()
	f, err := os.Open("../testdata/luminance/luminance.json")
	if err != nil {
		t.Fatalf("open luminance goldens: %v", err)
	}
	t.Cleanup(func() {
		if err := f.Close(); err != nil {
			t.Errorf("close luminance goldens: %v", err)
		}
	})

	var goldens struct {
		Cases     []goldenLuminanceCase `json:"cases"`
		Luminance []float64             `json:"luminance"`
		Resize    int                   `json:"resize"`
	}
	if err := json.NewDecoder(f).Decode(&goldens); err != nil {
		t.Fatalf("decode luminance goldens: %v", err)
	}
	if len(goldens.Cases) == 0 {
		t.Fatalf("no luminance golden cases loaded")
	}
	return goldens.Luminance, goldens.Resize, goldens.Cases
}

// TestHashFromLuminanceMatchesPerlPHashScalarGolden verifies that a checked-in
// luminance block run through the exported dct package and then the bit
// pipeline — the HashFromLuminance composition — yields the same Hash hex as
// Image::PHash 0.3's pHash scalar-context return value for the same luminance
// and options. The goldens in ../testdata/luminance/luminance.json were
// generated by driving the real installed Image::PHash 0.3 pHash method (in
// scalar context, so it returns b2h of the bit string) through a fake $self
// carrying the shared 32x32 row-major luminance fixture (LCG
// ($i*1103515245+12345) mod 2^32, low byte) as pixels and no cached dct, so
// Image::PHash computes Math::DCT dct2d itself before the geometry/reduce/
// method selection, the mirror and mirrorproof transforms, and the threshold
// conversion. The case matrix covers NxN and bit-count geometry, the reduce
// flag, all five methods, the median/average_x extras and the non-reduce NxN
// skip flag, and the mirror and mirrorproof DCT transforms — the same option
// set as the precomputed-DCT pipeline goldens, now through the real DCT of a
// raw luminance block.
func TestHashFromLuminanceMatchesPerlPHashScalarGolden(t *testing.T) {
	luminance, resize, cases := loadLuminanceGoldens(t)
	for _, tc := range cases {
		t.Run(tc.Name, func(t *testing.T) {
			got, err := phash.HashFromLuminance(luminance, resize, phash.Options{
				Geometry:    tc.Geometry,
				Reduce:      tc.Reduce,
				Method:      tc.Method,
				Mirror:      tc.Mirror,
				MirrorProof: tc.MirrorProof,
			})
			if err != nil {
				t.Fatalf("HashFromLuminance(%+v) returned an unexpected error: %v", tc, err)
			}
			if got.Hex() != tc.Hex {
				t.Errorf("HashFromLuminance(%+v).Hex() = %q, want %q (Image::PHash scalar-context pHash golden for the luminance block)",
					tc, got.Hex(), tc.Hex)
			}
		})
	}
}

// luminanceN is the edge length of the fixed-pixel RGBA fixture the
// luminance extraction test runs over. The fixture is deliberately small so
// every expected value is written out explicitly.
const luminanceN = 4

// luminanceFixture is a fixed 4×4 RGBA fixture standing in for a resized
// image, listed in scan order (row-major, x fastest) as its (r, g, b) 0–255
// channels plus the expected Image::PHash 0.3 luminance (r*0.3 + g*0.59 +
// b*0.11). The channels ramp independently (r by x, g by y, b by x+y) and
// stay far from equal so each of the three weights is observable: the BT.601
// 0.299/0.587/0.114 formula differs by up to ~1.5 on this fixture. Each want
// is the exact float64 result of the formula, which reduces to 56.2 + 17.2x
// + 25.8y for these channels.
var luminanceFixture = []struct {
	r, g, b uint8
	want    float64
}{
	{40, 60, 80, 56.2},     // (0,0)
	{90, 60, 100, 73.4},    // (1,0)
	{140, 60, 120, 90.6},   // (2,0)
	{190, 60, 140, 107.8},  // (3,0)
	{40, 100, 100, 82},     // (0,1)
	{90, 100, 120, 99.2},   // (1,1)
	{140, 100, 140, 116.4}, // (2,1)
	{190, 100, 160, 133.6}, // (3,1)
	{40, 140, 120, 107.8},  // (0,2)
	{90, 140, 140, 125},    // (1,2)
	{140, 140, 160, 142.2}, // (2,2)
	{190, 140, 180, 159.4}, // (3,2)
	{40, 180, 140, 133.6},  // (0,3)
	{90, 180, 160, 150.8},  // (1,3)
	{140, 180, 180, 168},   // (2,3)
	{190, 180, 200, 185.2}, // (3,3)
}

// luminanceTolerance bounds the acceptable rounding between the extracted
// luminance and the fixture's expected value. The exact float64 formula and
// the written-out decimals agree to within 3e-14, so 1e-9 leaves ample room
// while still rejecting any backend other than 0.3/0.59/0.11 (BT.601 differs
// by up to ~1.5 on this fixture).
const luminanceTolerance = 1e-9

// luminanceFixtureImage builds the fixed 4×4 RGBA described by
// luminanceFixture, in scan order, with every pixel opaque.
func luminanceFixtureImage(t *testing.T) *image.RGBA {
	t.Helper()
	if len(luminanceFixture) != luminanceN*luminanceN {
		t.Fatalf("luminanceFixture has %d pixels, want %d (N*N)", len(luminanceFixture), luminanceN*luminanceN)
	}
	img := image.NewRGBA(image.Rect(0, 0, luminanceN, luminanceN))
	for i, px := range luminanceFixture {
		x, y := i%luminanceN, i/luminanceN
		img.SetRGBA(x, y, color.RGBA{R: px.r, G: px.g, B: px.b, A: 255})
	}
	return img
}

// TestLuminanceExtractsImagePHash030GrayscaleFromResizedRGBA verifies the
// luminance extraction step between resize and DCT: converting a fixed-pixel
// N×N RGBA fixture (standing in for a resized image) into grayscale floats
// must reproduce the Image::PHash 0.3 backend formula — r*0.3 + g*0.59 +
// b*0.11 on the 0–255 channels — in scan order (row-major, x fastest) with
// exactly N*N values, the input HashFromLuminance then hashes.
func TestLuminanceExtractsImagePHash030GrayscaleFromResizedRGBA(t *testing.T) {
	img := luminanceFixtureImage(t)
	got := phash.Luminance(img, luminanceN)

	if len(got) != luminanceN*luminanceN {
		t.Fatalf("Luminance(fixture, %d) returned %d values, want %d (N*N)", luminanceN, len(got), luminanceN*luminanceN)
	}
	for i, px := range luminanceFixture {
		if val := got[i]; math.Abs(val-px.want) > luminanceTolerance {
			x, y := i%luminanceN, i/luminanceN
			t.Errorf("Luminance(fixture, %d)[%d] (pixel (%d,%d) r=%d g=%d b=%d) = %g, want %g (Image::PHash 0.3 r*0.3 + g*0.59 + b*0.11)",
				luminanceN, i, x, y, px.r, px.g, px.b, val, px.want)
		}
	}
}
