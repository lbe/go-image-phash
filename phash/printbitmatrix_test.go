// goldenPrintBitMatrixCase is one fixture from the golden file in
// ../testdata/printbitmatrix: the options Image::PHash 0.3's printbitmatrix
// method was called with (geometry/reduce/method/mirror/mirrorproof plus the
// raw separator/filler option values, exactly as invoked, so an unset
// separator/filler is the empty string) and the returned print-friendly bit
// matrix string, for the shared fixture DCT matrix.
type goldenPrintBitMatrixCase struct {
	Name        string `json:"name"`
	Geometry    string `json:"geometry"`
	Reduce      bool   `json:"reduce"`
	Method      string `json:"method"`
	Mirror      bool   `json:"mirror"`
	MirrorProof bool   `json:"mirrorproof"`
	Separator   string `json:"separator"`
	Filler      string `json:"filler"`
	Output      string `json:"output"`
}

// loadPrintBitMatrixGoldens opens and decodes
// ../testdata/printbitmatrix/printbitmatrix.json, failing the test when the
// file is missing, malformed, or carries no cases. It returns the shared
// fixture DCT matrix, the resize value, and the golden cases.
func loadPrintBitMatrixGoldens(t *testing.T) (dct []float64, resize int, cases []goldenPrintBitMatrixCase) {
	t.Helper()
	f, err := os.Open("../testdata/printbitmatrix/printbitmatrix.json")
	if err != nil {
		t.Fatalf("open printbitmatrix goldens: %v", err)
	}
	t.Cleanup(func() {
		if err := f.Close(); err != nil {
			t.Errorf("close printbitmatrix goldens: %v", err)
		}
	})

	var goldens struct {
		Cases  []goldenPrintBitMatrixCase `json:"cases"`
		DCT    []float64                  `json:"dct"`
		Resize int                        `json:"resize"`
	}
	if err := json.NewDecoder(f).Decode(&goldens); err != nil {
		t.Fatalf("decode printbitmatrix goldens: %v", err)
	}
	if len(goldens.Cases) == 0 {
		t.Fatalf("no printbitmatrix golden cases loaded")
	}
	return goldens.DCT, goldens.Resize, goldens.Cases
}

// stripNonBits removes every character that is not '0' or '1' from a printed
// matrix, recovering the underlying bit string in the order the formatter
// consumed it. For NxN grid geometries the consumption order is row-major, so
// the stripped string is exactly the bit string pHash produced; for bit-count
// geometries the triangle layout reorders the bits, so only grid cases can be
// cross-checked against the pipeline hex goldens.
func stripNonBits(matrix string) string {
	var b strings.Builder
	b.Grow(len(matrix))
	for _, r := range matrix {
		if r == '0' || r == '1' {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// instanceDCT computes the row-major DCT coefficient grid the instance's own
// hash pipeline DCTs: the exported 2D DCT of the instance's on-demand scaled
// image's luminance, i.e. exactly the vector p.dct() caches. It is built only
// from independently verified pieces — ReducedImage, Luminance, and the
// exported dct package — so the method's wiring of the instance's own DCT and
// resize into the formatter can be checked against the golden-verified
// PrintBitMatrixFromDCT path. The exported DCT_2D writes through its result
// pointer and transforms the input in place on its fast paths, so the
// luminance block is copied first.
func instanceDCT(t *testing.T, p *phash.PHash, n int) []float64 {
	t.Helper()
	luminance := phash.Luminance(p.ReducedImage().(*image.RGBA), n)
	input := append([]float64(nil), luminance...)
	coeffs := make([]float64, len(input))
	dct.DCT_2D(&input, n, &coeffs)
	return coeffs
}

// pipelineKey identifies an Image::PHash pHash option combination by the
// hashing options only (separator/filler do not change the bits), so a
// printed grid can be cross-checked against the scalar-context hex goldens in
// testdata/pipeline.
type pipelineKey struct {
	geometry    string
	reduce      bool
	method      string
	mirror      bool
	mirrorproof bool
}

// TestPrintBitMatrixRendersPrintableBitMatrixForGivenOptions verifies the
// PrintBitMatrix helper, the Go analogue of Image::PHash 0.3's printbitmatrix
// method (which runs the full pHash bit pipeline and lays the resulting bits
// out as a print-friendly matrix):
//
//   - PrintBitMatrixFromDCT over the shared 32x32 DCT fixture matches the
//     printbitmatrix goldens in ../testdata/printbitmatrix, which were
//     generated by driving the real installed Image::PHash 0.3 printbitmatrix
//     through a fake $self carrying that same fixture — NOT the Perl util.t
//     Imager file-based M31.jpg strings — across separator, filler, and
//     geometry cases: NxN grids with and without reduce (filler positions),
//     custom separator/filler strings, the bit-count triangle layout, the
//     median/average_x extras, and the mirror/mirrorproof DCT variants;
//   - the raw separator/filler option values are recorded in the goldens
//     exactly as invoked (empty when unset), so the implementation must apply
//     Perl's `separator || ”` and `filler || ' '` defaults;
//   - the bits rendered in the NxN grid cases rehash to the scalar-context
//     pHash hex goldens in ../testdata/pipeline for the same options, tying
//     the printed matrix to the already-golden-verified Go pipeline (the
//     bit-count triangle layout reorders bits, so only grid geometries can
//     be cross-checked this way);
//   - the PHash method renders the instance's own cached DCT: for the
//     checked-in 32x32 synthetic fixture, p.PrintBitMatrix(opts) equals
//     PrintBitMatrixFromDCT over the instance's own luminance DCT with the
//     same opts (default, a reduce grid with separator/filler, and a
//     bit-count geometry);
//   - Options{Mirror: true, MirrorProof: true} errors like Perl's _mirroring
//     croak on both entry points, and a geometry larger than the resize
//     errors like Perl's "geometry cannot be greater than the resize value"
//     croak.
func TestPrintBitMatrixRendersPrintableBitMatrixForGivenOptions(t *testing.T) {
	coeffs, resize, cases := loadPrintBitMatrixGoldens(t)

	t.Run("output matches the Perl printbitmatrix goldens from the shared DCT fixture", func(t *testing.T) {
		for _, tc := range cases {
			t.Run(tc.Name, func(t *testing.T) {
				opts := phash.Options{
					Geometry:    tc.Geometry,
					Reduce:      tc.Reduce,
					Method:      tc.Method,
					Mirror:      tc.Mirror,
					MirrorProof: tc.MirrorProof,
					Separator:   tc.Separator,
					Filler:      tc.Filler,
				}
				got, err := phash.PrintBitMatrixFromDCT(coeffs, resize, opts)
				if err != nil {
					t.Fatalf("PrintBitMatrixFromDCT(%+v) returned an unexpected error: %v", tc, err)
				}
				if got != tc.Output {
					t.Errorf("PrintBitMatrixFromDCT(%+v) = %q, want %q (Image::PHash 0.3 printbitmatrix golden, generated from the shared DCT fixture)",
						tc, got, tc.Output)
				}
			})
		}
	})

	t.Run("printed NxN grid bits match the pipeline hex goldens", func(t *testing.T) {
		pipelineDCT, pipelineResize, pipelineCases := loadPipelineGoldens(t)
		if pipelineResize != resize || !reflect.DeepEqual(pipelineDCT, coeffs) {
			t.Fatalf("printbitmatrix goldens carry a different DCT fixture than the pipeline goldens (resize %d vs %d); the fixtures must be the same 32x32 matrix",
				resize, pipelineResize)
		}
		wantHex := make(map[pipelineKey]string)
		for _, pc := range pipelineCases {
			wantHex[pipelineKey{geometry: pc.Geometry, reduce: pc.Reduce, method: pc.Method, mirror: pc.Mirror, mirrorproof: pc.MirrorProof}] = pc.Hex
		}
		checked := 0
		for _, tc := range cases {
			if !strings.Contains(tc.Geometry, "x") {
				continue // bit-count triangle layout reorders the bits
			}
			hex, ok := wantHex[pipelineKey{geometry: tc.Geometry, reduce: tc.Reduce, method: tc.Method, mirror: tc.Mirror, mirrorproof: tc.MirrorProof}]
			if !ok {
				continue
			}
			checked++
			if got := phash.BitsToHex(stripNonBits(tc.Output)); got != hex {
				t.Errorf("bits rendered in the %q grid rehash to %q, want the pipeline golden %q (the printed matrix must carry exactly the bits Image::PHash pHash produces)",
					tc.Name, got, hex)
			}
		}
		if checked == 0 {
			t.Fatal("no grid case matched a pipeline golden; the bits cross-check did not run")
		}
	})

	t.Run("method renders the instance's own DCT through the same formatter", func(t *testing.T) {
		golden := loadSyntheticGolden(t)
		img := syntheticFixtureImage(t, golden)
		p, err := phash.NewFromImage(img, 0, phash.Options{})
		if err != nil {
			t.Fatalf("NewFromImage(synthetic image, 0, Options{}) returned an unexpected error: %v", err)
		}
		n := golden.Resize
		instance := instanceDCT(t, p, n)
		optionSets := []struct {
			name string
			opts phash.Options
		}{
			{"default 8x8 average", phash.Options{}},
			{"4x4 reduce with separator and filler", phash.Options{Geometry: "4x4", Reduce: true, Separator: "|", Filler: "x"}},
			{"bit-count 8", phash.Options{Geometry: "8"}},
		}
		for _, tc := range optionSets {
			t.Run(tc.name, func(t *testing.T) {
				want, err := phash.PrintBitMatrixFromDCT(instance, n, tc.opts)
				if err != nil {
					t.Fatalf("PrintBitMatrixFromDCT(instance DCT, %d, %+v) returned an unexpected error: %v", n, tc.opts, err)
				}
				got, err := p.PrintBitMatrix(tc.opts)
				if err != nil {
					t.Fatalf("PrintBitMatrix(%+v) returned an unexpected error: %v", tc.opts, err)
				}
				if got != want {
					t.Errorf("PrintBitMatrix(%+v) = %q, want %q (the instance's own DCT %v rendered by the golden-verified formatter)",
						tc.opts, got, want, previewDCT(instance))
				}
			})
		}
	})

	t.Run("mirror with mirrorproof errors like the Perl _mirroring croak", func(t *testing.T) {
		opts := phash.Options{Mirror: true, MirrorProof: true}
		if got, err := phash.PrintBitMatrixFromDCT(coeffs, resize, opts); err == nil {
			t.Errorf("PrintBitMatrixFromDCT(mirror+mirrorproof) returned %q with no error; want an exclusivity error (Image::PHash printbitmatrix's pHash croaks: options mirror and mirrorproof are mutually exclusive)",
				got)
		}
		golden := loadSyntheticGolden(t)
		p, err := phash.NewFromImage(syntheticFixtureImage(t, golden), 0, phash.Options{})
		if err != nil {
			t.Fatalf("NewFromImage(synthetic image, 0, Options{}) returned an unexpected error: %v", err)
		}
		if got, err := p.PrintBitMatrix(opts); err == nil {
			t.Errorf("PrintBitMatrix(mirror+mirrorproof) returned %q with no error; want an exclusivity error (Image::PHash printbitmatrix's pHash croaks: options mirror and mirrorproof are mutually exclusive)",
				got)
		}
	})

	t.Run("geometry larger than the resize errors like Perl", func(t *testing.T) {
		if got, err := phash.PrintBitMatrixFromDCT(coeffs, resize, phash.Options{Geometry: "64x64"}); err == nil {
			t.Errorf("PrintBitMatrixFromDCT(Geometry: %q, resize %d) returned %q with no error; want a geometry-vs-resize rejection (Image::PHash: geometry cannot be greater than the resize value (%d))",
				"64x64", resize, got, resize)
		}
	})
}
