// gradientFixture returns a 5×5 RGBA whose pixel at (x, y) is the two-axis
// gradient color (x*51, y*51, 128, 255) with x, y in [0, 5). Scaling this
// with golang.org/x/image/draw's ApproxBiLinear produces a smooth ramp that a
// nearest-neighbor or naive sampler would render with different values, so
// the pixel checks below can tell the default scaler apart from any other.
func gradientFixture() *image.RGBA {
	src := image.NewRGBA(image.Rect(0, 0, 5, 5))
	for y := 0; y < 5; y++ {
		for x := 0; x < 5; x++ {
			src.SetRGBA(x, y, color.RGBA{R: uint8(x * 51), G: uint8(y * 51), B: 128, A: 255})
		}
	}
	return src
}

// ramp8 is the ApproxBiLinear column/row ramp produced when the 5×5
// gradientFixture is scaled to 8×8: 0, 22, 54, 86, 118, 150, 182, 204 (32x-10
// in the interior with the two boundary samples preserved).
func ramp8(i int) uint8 {
	switch i {
	case 0:
		return 0
	case 7:
		return 204
	default:
		return uint8(32*i - 10)
	}
}

// recordingResizer is a Resizer that records the arguments of every call and
// hands back a caller-provided destination, letting a test observe that an
// optional Resizer is routed to instead of the default scaler.
type recordingResizer struct {
	calls int
	src   image.Image
	n     int
	dst   *image.RGBA
}

func (r *recordingResizer) Resize(src image.Image, n int) *image.RGBA {
	r.calls++
	r.src = src
	r.n = n
	return r.dst
}

// TestDefaultResizerScalesFixtureToNxNWithApproxBiLinear verifies the default
// nil-Resizer path: Resize scales a fixture image to an n×n *image.RGBA whose
// Bounds are exactly (0, 0, n, n) and whose pixels equal the deterministic
// output of golang.org/x/image/draw's ApproxBiLinear scaler for the same
// source and size. The expected values were generated by running that scaler
// over the fixture (the output is identical on x/image v0.18.0 and v0.42.0);
// both a downscale (5×5 → 4×4) and an upscale (5×5 → 8×8) are covered, and
// the default path must hand back a release func so the pooled buffer can be
// returned to the pool.
func TestDefaultResizerScalesFixtureToNxNWithApproxBiLinear(t *testing.T) {
	src := gradientFixture()

	t.Run("downscale 5x5 to 4x4", func(t *testing.T) {
		const n = 4
		dst, release := phash.Resize(src, n, nil)
		if release == nil {
			t.Fatalf("Resize(fixture, %d, nil) returned a nil release func; the caller must be able to return the pooled buffer", n)
		}
		defer release()

		if dst == nil {
			t.Fatalf("Resize(fixture, %d, nil) returned a nil destination", n)
		}
		if got, want := dst.Bounds(), image.Rect(0, 0, n, n); !got.Eq(want) {
			t.Fatalf("Resize(fixture, %d, nil).Bounds() = %v, want %v", n, got, want)
		}

		// ApproxBiLinear of the 5×5 gradient at 4×4: R ramps 6,70,134,198
		// across columns and G across rows; B and A stay 128 and 255.
		for y := 0; y < n; y++ {
			for x := 0; x < n; x++ {
				want := color.RGBA{R: uint8(6 + 64*x), G: uint8(6 + 64*y), B: 128, A: 255}
				if got := dst.RGBAAt(x, y); got != want {
					t.Errorf("Resize(fixture, %d, nil) pixel (%d,%d) = %v, want %v (ApproxBiLinear output)", n, x, y, got, want)
				}
			}
		}
	})

	t.Run("upscale 5x5 to 8x8", func(t *testing.T) {
		const n = 8
		dst, release := phash.Resize(src, n, nil)
		defer release()

		if dst == nil {
			t.Fatalf("Resize(fixture, %d, nil) returned a nil destination", n)
		}
		if got, want := dst.Bounds(), image.Rect(0, 0, n, n); !got.Eq(want) {
			t.Fatalf("Resize(fixture, %d, nil).Bounds() = %v, want %v", n, got, want)
		}

		// ApproxBiLinear upscale: R ramps 0,22,54,...,182,204 across columns
		// and G across rows; B and A stay 128 and 255.
		for y := 0; y < n; y++ {
			for x := 0; x < n; x++ {
				want := color.RGBA{R: ramp8(x), G: ramp8(y), B: 128, A: 255}
				if got := dst.RGBAAt(x, y); got != want {
					t.Errorf("Resize(fixture, %d, nil) pixel (%d,%d) = %v, want %v (ApproxBiLinear output)", n, x, y, got, want)
				}
			}
		}
	})

	t.Run("upscale 5x5 to 64x64 uses a fresh buffer when the pool canvas is too small", func(t *testing.T) {
		const n = 64
		dst, release := phash.Resize(src, n, nil)
		defer release()
		if dst == nil {
			t.Fatalf("Resize(fixture, %d, nil) returned a nil destination", n)
		}
		if got, want := dst.Bounds(), image.Rect(0, 0, n, n); !got.Eq(want) {
			t.Fatalf("Resize(fixture, %d, nil).Bounds() = %v, want %v", n, got, want)
		}
	})
}

// TestResizeRoutesThroughOptionalResizer verifies the optional Resizer: when
// a non-nil Resizer is passed, Resize must invoke its Resize method with the
// exact source and size and return the destination it produced, untouched by
// the default scaler and the pool.
func TestResizeRoutesThroughOptionalResizer(t *testing.T) {
	src := gradientFixture()
	customDst := image.NewRGBA(image.Rect(0, 0, 8, 8))
	rec := &recordingResizer{dst: customDst}

	dst, release := phash.Resize(src, 8, rec)
	if release == nil {
		t.Fatalf("Resize with a provided Resizer returned a nil release func; a safe no-op release must still be returned")
	}
	defer release()

	if rec.calls != 1 {
		t.Fatalf("provided Resizer invoked %d times, want 1 (nil/default must not be used when a Resizer is supplied)", rec.calls)
	}
	if rec.src != src {
		t.Errorf("provided Resizer received src %T, want the exact fixture passed to Resize", rec.src)
	}
	if rec.n != 8 {
		t.Errorf("provided Resizer received n = %d, want 8", rec.n)
	}
	if dst != customDst {
		t.Errorf("Resize returned %p, want the provided Resizer's destination %p returned unchanged", dst, customDst)
	}
	if got, want := dst.Bounds(), image.Rect(0, 0, 8, 8); !got.Eq(want) {
		t.Errorf("Resize with a provided Resizer returned Bounds %v, want %v", got, want)
	}
}

// TestDefaultResizeChecksOutDistinctBuffersUntilReleased verifies the pool
// checkout contract behind the default scaler: a buffer handed out by Resize
// stays checked out until the caller's release func runs, so two simultaneous
// checkouts must be distinct *image.RGBA objects with no shared backing
// store. If the scaler returned the first buffer to the pool between the two
// calls — or handed out two views of one pooled canvas — the buffers would
// alias, and mutating one would corrupt the other, which is exactly the
// retention hazard the acceptance forbids for ReducedImage/DCT caches. The
// default resize size (32) is used so the check exercises the pooled canvas
// geometry at its natural size.
func TestDefaultResizeChecksOutDistinctBuffersUntilReleased(t *testing.T) {
	src := gradientFixture()
	const n = 32

	a, releaseA := phash.Resize(src, n, nil)
	b, releaseB := phash.Resize(src, n, nil)
	defer releaseA()
	defer releaseB()

	if a == nil || b == nil {
		t.Fatalf("default Resize returned a nil buffer (a nil = %v, b nil = %v)", a == nil, b == nil)
	}
	if got, want := a.Bounds(), image.Rect(0, 0, n, n); !got.Eq(want) {
		t.Fatalf("first checked-out buffer Bounds = %v, want %v", got, want)
	}
	if got, want := b.Bounds(), image.Rect(0, 0, n, n); !got.Eq(want) {
		t.Fatalf("second checked-out buffer Bounds = %v, want %v", got, want)
	}
	if a == b {
		t.Fatalf("two simultaneous default Resize checkouts returned the same buffer %p; the first must stay checked out until released", a)
	}

	// Snapshot b, mark every pixel of a, and require b to be untouched: any
	// shared backing store between the two checkouts shows up here.
	snapshot := make([]color.RGBA, n*n)
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			snapshot[y*n+x] = b.RGBAAt(x, y)
		}
	}
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			a.SetRGBA(x, y, color.RGBA{R: 255, A: 255})
		}
	}
	for y := 0; y < n; y++ {
		for x := 0; x < n; x++ {
			if got := b.RGBAAt(x, y); got != snapshot[y*n+x] {
				t.Fatalf("mutating the first checked-out buffer changed the second at (%d,%d): %v -> %v; checkouts must not share backing store", x, y, snapshot[y*n+x], got)
			}
		}
	}
}

// TestDefaultResizePathHasNoBildDependency verifies the resize path does not
// pull in the bild library: the module's go.mod must not require
// github.com/anthonynsimon/bild (the module-wide import-graph ban is enforced
// by internal/repointegrity; this unit-level check pins the same rule for the
// default-resizer cycle).
func TestDefaultResizePathHasNoBildDependency(t *testing.T) {
	mod, err := os.ReadFile("../go.mod")
	if err != nil {
		t.Fatalf("read go.mod: %v", err)
	}
	if strings.Contains(string(mod), "github.com/anthonynsimon/bild") {
		t.Error("go.mod must not require github.com/anthonynsimon/bild; the default resizer uses golang.org/x/image/draw.ApproxBiLinear")
	}
}
