package phash

import (
	"encoding/json"
	"os"
	"testing"
)

// goldenMethodCase is one fixture from a method golden file in
// ../testdata/methods: the selected primary coefficient list, the Perl $skip
// flag, the @extra list Perl feeds the threshold for methods whose $x_mult is
// true (left nil for average, whose $x_mult is false), and the golden bit
// string.
type goldenMethodCase struct {
	Name    string    `json:"name"`
	Skip    int       `json:"skip"`
	Primary []float64 `json:"primary"`
	Extra   []float64 `json:"extra"`
	Want    string    `json:"want"`
}

// loadMethodGoldens opens and decodes the named golden file in
// ../testdata/methods, failing the test when the file is missing, malformed,
// or carries no cases.
func loadMethodGoldens(t *testing.T, name string) []goldenMethodCase {
	t.Helper()
	f, err := os.Open("../testdata/methods/" + name + ".json")
	if err != nil {
		t.Fatalf("open %s goldens: %v", name, err)
	}
	t.Cleanup(func() {
		if err := f.Close(); err != nil {
			t.Errorf("close %s goldens: %v", name, err)
		}
	})

	var goldens struct {
		Cases []goldenMethodCase `json:"cases"`
	}
	if err := json.NewDecoder(f).Decode(&goldens); err != nil {
		t.Fatalf("decode %s goldens: %v", name, err)
	}
	if len(goldens.Cases) == 0 {
		t.Fatalf("no %s golden cases loaded", name)
	}
	return goldens.Cases
}

// TestAverageMethodConvertsSelectedDCTCoeffsToBits verifies that the average
// method turns a selected list of DCT coefficients into the same bit string
// as Image::PHash 0.3's _apply_average for fixed coefficient fixtures. The
// fixtures in ../testdata/methods/average.json were generated by running the
// verbatim _apply_average subroutine from lib/Image/PHash.pm (v0.3) over
// selections made by Image::PHash's own pHash loops, so each case carries the
// primary coefficient list, the Perl $skip flag, and the golden bit string.
// The non-reduce NxN case carries skip=1: DC (primary[0]) is excluded from
// the average threshold but still produces the first bit of the string; the
// reduce and bit-count cases carry skip=0. The average method receives no
// extras ($x_mult is false for it in Perl), so the test passes an empty extra
// list.
func TestAverageMethodConvertsSelectedDCTCoeffsToBits(t *testing.T) {
	for _, tc := range loadMethodGoldens(t, "average") {
		t.Run(tc.Name, func(t *testing.T) {
			got := applyAverage(tc.Primary, tc.Skip, nil)
			if got != tc.Want {
				t.Errorf("applyAverage(skip=%d) = %q (len %d), want %q (len %d) (Image::PHash average golden)",
					tc.Skip, got, len(got), tc.Want, len(tc.Want))
			}
		})
	}
}

// TestAverageXMethodConvertsSelectedDCTCoeffsToBits verifies that the
// average_x method turns a selected list of DCT coefficients into the same
// bit string as Image::PHash 0.3's average_x method for fixed coefficient
// fixtures. Image::PHash registers average_x as \&_apply_average (the same
// mean threshold as average) but with $x_mult true, so its pHash loop feeds
// the threshold the same @extra lists as the median method; each fixture in
// ../testdata/methods/average_x.json therefore carries the primary
// coefficient list, the Perl @extra list, the Perl $skip flag, and the
// golden bit string. The non-reduce NxN case carries skip=1: DC (primary[0])
// is excluded from the average threshold but still produces the first bit;
// the reduce and bit-count cases carry skip=0. The goldens were generated by
// running the verbatim _apply_average subroutine from lib/Image/PHash.pm
// (v0.3) over selections made by Image::PHash's own pHash loops with the
// method set to average_x, so the extras are exactly what Perl supplies.
func TestAverageXMethodConvertsSelectedDCTCoeffsToBits(t *testing.T) {
	for _, tc := range loadMethodGoldens(t, "average_x") {
		t.Run(tc.Name, func(t *testing.T) {
			got := applyAverageX(tc.Primary, tc.Skip, tc.Extra)
			if got != tc.Want {
				t.Errorf("applyAverageX(skip=%d, %d extras) = %q (len %d), want %q (len %d) (Image::PHash average_x golden)",
					tc.Skip, len(tc.Extra), got, len(got), tc.Want, len(tc.Want))
			}
		})
	}
}

