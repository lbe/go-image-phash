package phash

import (
	"encoding/json"
	"os"
	"reflect"
	"testing"
)

// goldenMirrorCase is one fixture from a golden file in ../testdata/mirror:
// the input row-major DCT coefficient vector and the vectors Image::PHash
// 0.3's _dct_mirror and _dct_mirrorproof produce from it.
type goldenMirrorCase struct {
	Name        string    `json:"name"`
	DCT         []float64 `json:"dct"`
	Mirror      []float64 `json:"mirror"`
	MirrorProof []float64 `json:"mirrorproof"`
}

// loadMirrorGoldens opens and decodes the named golden file in
// ../testdata/mirror, failing the test when the file is missing, malformed,
// or carries no cases.
func loadMirrorGoldens(t *testing.T, name string) []goldenMirrorCase {
	t.Helper()
	f, err := os.Open("../testdata/mirror/" + name + ".json")
	if err != nil {
		t.Fatalf("open %s goldens: %v", name, err)
	}
	t.Cleanup(func() {
		if err := f.Close(); err != nil {
			t.Errorf("close %s goldens: %v", name, err)
		}
	})

	var goldens struct {
		Cases []goldenMirrorCase `json:"cases"`
	}
	if err := json.NewDecoder(f).Decode(&goldens); err != nil {
		t.Fatalf("decode %s goldens: %v", name, err)
	}
	if len(goldens.Cases) == 0 {
		t.Fatalf("no %s golden cases loaded", name)
	}
	return goldens.Cases
}

// TestMirrorTransformsDCTCoefficientsAsImagePHashDoes verifies that the
// mirror transform turns a row-major DCT coefficient vector into the same
// vector as Image::PHash 0.3's _dct_mirror for a fixed fixture. The fixture
// in ../testdata/mirror/mirror.json was generated by running the verbatim
// _dct_mirror subroutine from lib/Image/PHash.pm (v0.3) over the same 32x32
// row-major DCT fixture the method goldens use (DC 100.0 at index 0 plus a
// deterministic spread of AC coefficients), and was cross-checked against the
// installed Image::PHash module's _dct_mirror. _dct_mirror negates every
// other coefficient starting from the second (odd 0-based indices) and keeps
// the rest, so the mirrored vector must be a fresh slice matching the golden
// at every one of the 1024 positions.
func TestMirrorTransformsDCTCoefficientsAsImagePHashDoes(t *testing.T) {
	for _, tc := range loadMirrorGoldens(t, "mirror") {
		t.Run(tc.Name, func(t *testing.T) {
			got := mirrorDCT(tc.DCT)
			if !reflect.DeepEqual(got, tc.Mirror) {
				t.Errorf("mirrorDCT() = %v (len %d), want %v (len %d) (Image::PHash _dct_mirror golden)",
					shorten(got), len(got), shorten(tc.Mirror), len(tc.Mirror))
			}
		})
	}
}

// TestMirrorproofTransformsDCTCoefficientsAsImagePHashDoes verifies that the
// mirrorproof transform turns a row-major DCT coefficient vector into the same
// vector as Image::PHash 0.3's _dct_mirrorproof for the same 32x32 fixture the
// mirror goldens use. The mirrorproof array in
// ../testdata/mirror/mirror.json was generated by running the verbatim
// _dct_mirrorproof subroutine from lib/Image/PHash.pm (v0.3) over the same
// row-major DCT fixture, and the subroutine source matches the installed
// module's. _dct_mirrorproof takes the absolute value of every other
// coefficient starting from the second (odd 0-based indices) and keeps the
// rest, so the mirrorproof vector must be a fresh slice matching the golden at
// every one of the 1024 positions.
func TestMirrorproofTransformsDCTCoefficientsAsImagePHashDoes(t *testing.T) {
	for _, tc := range loadMirrorGoldens(t, "mirror") {
		t.Run(tc.Name, func(t *testing.T) {
			got := mirrorproofDCT(tc.DCT)
			if !reflect.DeepEqual(got, tc.MirrorProof) {
				t.Errorf("mirrorproofDCT() = %v (len %d), want %v (len %d) (Image::PHash _dct_mirrorproof golden)",
					shorten(got), len(got), shorten(tc.MirrorProof), len(tc.MirrorProof))
			}
		})
	}
}

// shorten returns a compact preview of a float slice: the full slice when it
// is short, otherwise its first few elements followed by an ellipsis marker.
func shorten(v []float64) []float64 {
	const preview = 6
	if len(v) <= preview {
		return v
	}
	return v[:preview]
}
