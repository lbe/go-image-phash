package phash_test

import (
	"encoding/json"
	"image"
	"image/color"
	"os"
	"testing"

	"github.com/lbe/go-image-phash/phash"
)

// goldenSyntheticCase is the single case in the golden file
// ../testdata/synthetic/synthetic.json: the options Image::PHash 0.3's pHash
// method was called with (the empty/zero settings defaults: resize 32,
// geometry 8x8, method average) and the scalar-context return value (the b2h
// hex of the bit string) for the shared 32x32 synthetic RGBA image, hashed
// by Image::PHash through its own Math::DCT dct2d call.
type goldenSyntheticCase struct {
	Name        string `json:"name"`
	Geometry    string `json:"geometry"`
	Reduce      bool   `json:"reduce"`
	Method      string `json:"method"`
	Mirror      bool   `json:"mirror"`
	MirrorProof bool   `json:"mirrorproof"`
	Hex         string `json:"hex"`
}

// syntheticGolden is the checked-in synthetic-image golden: the fixed 32x32
// RGBA fixture's channel planes (row-major, x fastest) plus the expected
// hashes for the cases that were run through Image::PHash.
type syntheticGolden struct {
	Resize int                   `json:"resize"`
	R      []uint8               `json:"r"`
	G      []uint8               `json:"g"`
	B      []uint8               `json:"b"`
	Cases  []goldenSyntheticCase `json:"cases"`
}

// loadSyntheticGolden opens and decodes ../testdata/synthetic/synthetic.json,
// failing the test when the file is missing, malformed, or carries no cases.
// It returns the golden, whose channel planes and expected hex are the
// checked-in Perl golden the NewFromImage pipeline must reproduce.
func loadSyntheticGolden(t *testing.T) *syntheticGolden {
	t.Helper()
	f, err := os.Open("../testdata/synthetic/synthetic.json")
	if err != nil {
		t.Fatalf("open synthetic-image goldens: %v", err)
	}
	t.Cleanup(func() {
		if err := f.Close(); err != nil {
			t.Errorf("close synthetic-image goldens: %v", err)
		}
	})

	var golden syntheticGolden
	if err := json.NewDecoder(f).Decode(&golden); err != nil {
		t.Fatalf("decode synthetic-image goldens: %v", err)
	}
	if len(golden.Cases) == 0 {
		t.Fatalf("no synthetic-image golden cases loaded")
	}
	n := golden.Resize * golden.Resize
	if len(golden.R) != n || len(golden.G) != n || len(golden.B) != n {
		t.Fatalf("synthetic golden channel planes have lengths r=%d g=%d b=%d, want %d (N*N)",
			len(golden.R), len(golden.G), len(golden.B), n)
	}
	return &golden
}

// syntheticFixtureImage rebuilds the golden's fixed N×N RGBA image from the
// checked-in channel planes, in scan order (row-major, x fastest) with every
// pixel opaque. Its N×N size matches the default resize, so the NewFromImage
// pipeline's ApproxBiLinear resize is an identity and the hashed luminance is
// exactly the fixture's own pixels, the same block Image::PHash hashed.
func syntheticFixtureImage(t *testing.T, golden *syntheticGolden) *image.RGBA {
	t.Helper()
	n := golden.Resize
	img := image.NewRGBA(image.Rect(0, 0, n, n))
	for i, r := range golden.R {
		img.SetRGBA(i%n, i/n, color.RGBA{R: r, G: golden.G[i], B: golden.B[i], A: 255})
	}
	return img
}

// blackFixture returns an n×n fully black RGBA image whose hashed content is
// as different from the synthetic fixture as possible, so a hash computed
// from a pooled resize buffer that a later instance overwrote changes
// visibly.
func blackFixture(n int) *image.RGBA {
	img := image.NewRGBA(image.Rect(0, 0, n, n))
	for i := 0; i < n*n; i++ {
		img.Pix[i*4+3] = 255
	}
	return img
}

// TestNewFromImageBuildsPHashThatHashesAndRejectsInvalidResize verifies the
// image-object constructor and its hash method end to end:
//
//   - NewFromImage over the checked-in synthetic 32x32 image with empty/zero
//     Options (Image::PHash 0.3 defaults: resize 32, geometry 8x8, method
//     average) returns a PHash whose hash Hex equals the checked-in golden in
//     ../testdata/synthetic/synthetic.json (generated by the installed
//     Image::PHash 0.3 over the same pixels);
//   - the constructor rejects resize <= 5 exactly like the Perl constructor's
//     "resize > 5 expected." croak, while a non-positive resize still falls
//     back to the default 32;
//   - the mutually exclusive mirror/mirrorproof pair errors at hash time
//     through Validate;
//   - a hash result survives the pooled resize buffer being reused by another
//     instance: either the checkout is held for the instance lifetime or the
//     luminance is copied before the buffer is Put, so hashing again after a
//     second instance resized a different image must still yield the golden.
func TestNewFromImageBuildsPHashThatHashesAndRejectsInvalidResize(t *testing.T) {
	golden := loadSyntheticGolden(t)
	img := syntheticFixtureImage(t, golden)
	def := golden.Cases[0]

	t.Run("default options match the checked-in Perl golden", func(t *testing.T) {
		p, err := phash.NewFromImage(img, 0, phash.Options{})
		if err != nil {
			t.Fatalf("NewFromImage(synthetic image, 0, Options{}) returned an unexpected error: %v", err)
		}
		if p == nil {
			t.Fatalf("NewFromImage(synthetic image, 0, Options{}) returned a nil PHash")
		}
		h, err := p.PHash(phash.Options{})
		if err != nil {
			t.Fatalf("PHash(Options{}) returned an unexpected error: %v", err)
		}
		if got := h.Hex(); got != def.Hex {
			t.Errorf("NewFromImage(synthetic image, 0, Options{}).PHash(Options{}).Hex() = %q, want %q (Image::PHash 0.3 scalar-context golden %q for the synthetic image with default settings)",
				got, def.Hex, def.Name)
		}
	})

	t.Run("constructor rejects resize <= 5 like Image::PHash", func(t *testing.T) {
		for _, bad := range []int{1, 5} {
			if p, err := phash.NewFromImage(img, bad, phash.Options{}); err == nil {
				t.Errorf("NewFromImage(synthetic image, %d, Options{}) returned PHash %v with no error; want a resize rejection (Image::PHash: resize > 5 expected)", bad, p)
			}
		}
		for _, ok := range []int{0, 6, 32} {
			if _, err := phash.NewFromImage(img, ok, phash.Options{}); err != nil {
				t.Errorf("NewFromImage(synthetic image, %d, Options{}) returned an unexpected error: %v; want acceptance (non-positive resize defaults to 32, and any resize > 5 is allowed)", ok, err)
			}
		}
	})

	t.Run("mirror with mirrorproof errors at hash time", func(t *testing.T) {
		p, err := phash.NewFromImage(img, 0, phash.Options{})
		if err != nil {
			t.Fatalf("NewFromImage(synthetic image, 0, Options{}) returned an unexpected error: %v", err)
		}
		if _, err := p.PHash(phash.Options{Mirror: true, MirrorProof: true}); err == nil {
			t.Error("PHash(Options{Mirror: true, MirrorProof: true}) returned a hash with no error; want an exclusivity error (Image::PHash: options mirror and mirrorproof are mutually exclusive)")
		}
	})

	t.Run("hash survives pooled resize buffer reuse by another instance", func(t *testing.T) {
		a, err := phash.NewFromImage(img, 0, phash.Options{})
		if err != nil {
			t.Fatalf("NewFromImage(synthetic image, 0, Options{}) returned an unexpected error: %v", err)
		}
		aFirst, err := a.PHash(phash.Options{})
		if err != nil {
			t.Fatalf("first PHash(Options{}) returned an unexpected error: %v", err)
		}
		if got := aFirst.Hex(); got != def.Hex {
			t.Fatalf("first PHash(Options{}).Hex() = %q, want %q (Image::PHash 0.3 scalar-context golden)", got, def.Hex)
		}

		// A second instance over a very different image forces the default
		// scaler to check out (or freshly allocate) a resize buffer; if the
		// first instance's cached resize/DCT referenced a buffer that was Put
		// back to the pool, this call's overwrite corrupts it.
		b, err := phash.NewFromImage(blackFixture(golden.Resize), 0, phash.Options{})
		if err != nil {
			t.Fatalf("NewFromImage(black image, 0, Options{}) returned an unexpected error: %v", err)
		}
		bHash, err := b.PHash(phash.Options{})
		if err != nil {
			t.Fatalf("PHash(Options{}) on the black image returned an unexpected error: %v", err)
		}
		if bHash.Hex() == def.Hex {
			t.Fatalf("black image hashed to the synthetic fixture's golden %q; the images must hash differently for this corruption probe", def.Hex)
		}

		// The first instance must still reproduce the golden: if it held a
		// reference into the pooled buffer that the second instance's resize
		// reused and overwrote, this second hash would differ.
		aAgain, err := a.PHash(phash.Options{})
		if err != nil {
			t.Fatalf("second PHash(Options{}) returned an unexpected error: %v", err)
		}
		if got := aAgain.Hex(); got != def.Hex {
			t.Errorf("PHash(Options{}) after another instance reused the resize pool = %q, want %q (Image::PHash 0.3 scalar-context golden); the pooled resize buffer must not be Put while the instance's cached data still references it (hold the checkout for the instance lifetime or copy luminance before Put)",
				got, def.Hex)
		}
	})
}
